import { describe, expect, it } from 'vitest'
import { designDoubly, minDepthForYield, pickBars, reviewDoubly, singlyMax } from './doubly'

const near = (v: number, ref: number, tol = 0.01) => expect(Math.abs(v - ref)).toBeLessThanOrEqual(Math.abs(ref) * tol + 1e-9)

describe('doubly review — lecture examples', () => {
  it('Nilson Ex 3.12: both steels yield, φMn = 8500 in-k (εt taken at d = 24 as in the book)', () => {
    const r = reviewDoubly({ b: 12, d: 24, dt: 24, dp: 2.5, As: 7.62, Asp: 1.58, fc: 5, fy: 60 })
    expect(r.compYields).toBe(true)
    expect(r.method).toBe('both-yield')
    near(r.rhoCy, 0.0245, 0.01)
    near(r.a, 7.11, 0.005)
    near(r.c, 8.89, 0.005)
    near(r.epsT, 0.0051, 0.02)
    near(r.Mn, 9450, 0.002)
    near(r.phiMn * 12, 8500, 0.002)
  })

  it('Hassoun Ex 3.10: A′s does not yield → quadratic 47.6c² − 261.08c − 515.475 = 0, c = 7.026, Mn = 9040 in-k', () => {
    const r = reviewDoubly({ b: 14, d: 22.5, dt: 23, dp: 2.5, As: 7.62, Asp: 2.37, fc: 5, fy: 60 })
    expect(r.compYields).toBe(false)
    expect(r.method).toBe('quadratic')
    near(r.rhoCy, 0.02783, 0.005)
    near(r.quad!.A, 47.6, 0.001)
    near(r.quad!.B, -261.08, 0.001)
    near(r.quad!.C, -515.475, 0.001)
    near(r.c, 7.026, 0.002)
    near(r.fsp, 56.04, 0.003)
    near(r.Cc, 334.5, 0.003)
    near(r.Cs, 122.7, 0.003)
    near(r.Mn, 9040.3, 0.002)
    near(r.epsT, 0.00682, 0.01)
    near(r.phiMn * 12, 8136, 0.002)
  })

  it('Nilson Ex 3.13 handnote review (4 #9 + 2 #6, 10 × 20, d = 16, dt = 17.5): c = 6.74, f′s = 54.7, φMn = 2794 in-k', () => {
    const r = reviewDoubly({ b: 10, d: 16, dt: 17.5, dp: 2.5, As: 4.0, Asp: 0.88, fc: 4, fy: 60 })
    expect(r.compYields).toBe(false)
    near(r.c, 6.74, 0.003)
    near(r.fsp, 54.7, 0.003)
    near(r.Cc, 194.8, 0.003)
    near(r.Cs, 45.14, 0.005)
    near(r.Mn, 3167.9, 0.002)
    near(r.epsT, 0.00479, 0.01)
    near(r.phi, 0.882, 0.003)
    near(r.phiMn * 12, 2793.9, 0.003)
  })
})

