describe('doubly design', () => {
  it('Hassoun Ex 4.5 (10 × 22, fy 50, f′c 3, Mu 226.5 k-ft): As1 = 3.0, φMn1 = 2100 in-k, A′s = 0.86, As = 3.86', () => {
    const r = designDoubly({ b: 10, d: 18.5, dt: 19.5, dp: 2.5, fc: 3, fy: 50, Mu: 226.5 })
    expect(r.needed).toBe(true)
    near(r.sm.rho005, 0.01625, 0.002)
    near(r.sm.As1, 3.0, 0.005)
    near(r.sm.phiMn1 * 12, 2100.4, 0.003)
    expect(r.compYields).toBe(true)
    near(r.Asp, 0.86, 0.01)
    near(r.As, 3.86, 0.005)
  })
  it('Nilson Ex 3.13 (10 × 20, Mu = 2533 in-k): class shortcut A′s = 0.6, As = 3.49; strain mode gives the same As', () => {
    const y = designDoubly({ b: 10, d: 16, dt: 17.5, dp: 2.5, fc: 4, fy: 60, Mu: 2533 / 12, fsMode: 'assume-yield' })
    near(y.sm.As1, 2.89, 0.005)
    near(y.sm.phiMn1 * 12, 2099, 0.003)
    near(y.Asp, 0.6, 0.01)
    near(y.As, 3.49, 0.005)
    const s = designDoubly({ b: 10, d: 16, dt: 17.5, dp: 2.5, fc: 4, fy: 60, Mu: 2533 / 12 })
    expect(s.compYields).toBe(false)
    expect(s.Asp).toBeGreaterThan(y.Asp)
    near(s.As, 3.485, 0.003)
  })
  it('the recurring 12 × 25, d = 21, dt = 22.5, d′ = 2.5 design (2017-18 Q2(c), 2016-17 Q6(c), 2015-16 Q2(c))', () => {
    const base = { b: 12, d: 21, dt: 22.5, dp: 2.5, fy: 60 }
    const a = designDoubly({ ...base, fc: 4, Mu: 500 })
    expect(a.needed).toBe(true)
    near(a.sm.As1, 4.5518, 0.001)
    near(a.sm.phiMn1, 361.59, 0.001)
    near(a.fsp, 59.381, 0.001)
    near(a.Asp, 1.68, 0.003)
    near(a.As, 6.2144, 0.001)
    expect(a.ok).toBe(true)
    const b = designDoubly({ ...base, fc: 4, Mu: 625 })
    near(b.Asp, 3.1971, 0.002)
    near(b.As, 7.7159, 0.001)
    expect(b.review.phiMn).toBeGreaterThanOrEqual(625)
    const c = designDoubly({ ...base, fc: 3, Mu: 475 })
    near(c.sm.phiMn1, 271.19, 0.001)
    near(c.Asp, 2.4737, 0.002)
    near(c.As, 5.862, 0.001)
  })
  it('2023-24 Q2(c), 2021-22 Q6(c), 2020-21 Q2(c), Jan 2021 Q2', () => {
    const q = designDoubly({ b: 16, d: 26, dt: 27.5, dp: 2.5, fc: 5, fy: 60, Mu: 1200 })
    near(q.sm.phiMn1, 879.14, 0.001)
    near(q.As, 11.874, 0.001)
    near(designDoubly({ b: 14, d: 24, dt: 25.5, dp: 2.5, fc: 4, fy: 60, Mu: 700 }).As, 7.6092, 0.001)
    near(designDoubly({ b: 14, d: 25, dt: 26.5, dp: 2.5, fc: 4, fy: 60, Mu: 750 }).Asp, 1.5026, 0.002)
    near(designDoubly({ b: 14, d: 20, dt: 21.5, dp: 2.5, fc: 4, fy: 60, Mu: 475 }).Asp, 1.2134, 0.002)
  })
  it('compression steel not needed → singly design', () => {
    const r = designDoubly({ b: 12, d: 21, dt: 22.5, dp: 2.5, fc: 4, fy: 60, Mu: 300 })
    expect(r.needed).toBe(false)
    expect(r.comp).toBeNull()
    expect(r.review.phiMn).toBeGreaterThanOrEqual(300)
  })
  it('c-dt basis: c = 0.375 dt', () => {
    const s = singlyMax(12, 21, 22.5, 4, 60, 'c-dt')
    near(s.c, 8.4375, 1e-6)
    near(s.epsT, 0.005, 1e-6)
    near(s.phiMn1, 382.2, 0.003)
  })
})

